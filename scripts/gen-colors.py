"""Generate web/xlib/colors_data.c from X11's rgb.txt (MIT licence).

Usage: python3 scripts/gen-colors.py [/usr/share/X11/rgb.txt] > web/xlib/colors_data.c
"""
import sys

path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/X11/rgb.txt"
out = ["/* Generated by scripts/gen-colors.py from X11 rgb.txt. Do not edit. */",
       '#include "xw.h"', "", "const xw_color_name xw_color_names[] = {"]
seen = set()
for line in open(path):
    if line.startswith("!") or not line.strip():
        continue
    parts = line.split()
    r, g, b = (int(v) for v in parts[:3])
    name = " ".join(parts[3:])
    if name.lower() in seen:
        continue
    seen.add(name.lower())
    out.append('  {"%s", %d, %d, %d},' % (name, r, g, b))
out.append("  {0, 0, 0, 0}")
out.append("};")
print("\n".join(out))
