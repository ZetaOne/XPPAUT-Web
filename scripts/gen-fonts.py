"""Generate web/xlib/fonts_data.c from the X11 misc-fixed bitmap fonts.

The misc-fixed fonts (xfonts-base) are public domain. XPPAUT asks for
"fixed" and "6x13" by default (both the 6x13 semicondensed font); the other
sizes can be chosen with XPP's BIG_FONT/SMALL_FONT options.

Usage: python3 scripts/gen-fonts.py [/usr/share/fonts/X11/misc] > web/xlib/fonts_data.c
"""
import gzip
import struct
import sys

FONTDIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/X11/misc"

# (file stem, X font names that resolve to it)
FONTS = [
    ("5x7", ["5x7"]),
    ("5x8", ["5x8"]),
    ("6x9", ["6x9"]),
    ("6x10", ["6x10"]),
    ("6x12", ["6x12"]),
    ("6x13", ["6x13", "fixed"]),
    ("6x13B", ["6x13bold"]),
    ("7x13", ["7x13"]),
    ("7x13B", ["7x13bold"]),
    ("7x14", ["7x14"]),
    ("7x14B", ["7x14bold"]),
    ("8x13", ["8x13"]),
    ("8x13B", ["8x13bold"]),
    ("9x15", ["9x15"]),
    ("9x15B", ["9x15bold"]),
    ("9x18", ["9x18"]),
    ("9x18B", ["9x18bold"]),
    ("10x20", ["10x20"]),
]

PCF_ACCELERATORS, PCF_METRICS, PCF_BITMAPS = 2, 4, 8
PCF_BDF_ENCODINGS, PCF_BDF_ACCELERATORS = 32, 256
PCF_COMPRESSED_METRICS = 0x100


def parse_pcf(data):
    assert data[:4] == b"\x01fcp", "not a PCF file"
    (count,) = struct.unpack_from("<i", data, 4)
    tables = {}
    for i in range(count):
        t, fmt, size, off = struct.unpack_from("<iiii", data, 8 + 16 * i)
        tables[t] = (fmt, off)

    def table(t):
        fmt, off = tables[t]
        (fmt2,) = struct.unpack_from("<i", data, off)
        bo = ">" if fmt2 & 4 else "<"
        return fmt2, bo, off + 4

    # accelerators: font ascent/descent
    fmt, bo, p = table(PCF_BDF_ACCELERATORS if PCF_BDF_ACCELERATORS in tables else PCF_ACCELERATORS)
    ascent, descent = struct.unpack_from(bo + "ii", data, p + 8)

    # metrics
    fmt, bo, p = table(PCF_METRICS)
    metrics = []
    if fmt & PCF_COMPRESSED_METRICS:
        (n,) = struct.unpack_from(bo + "h", data, p)
        p += 2
        for i in range(n):
            lsb, rsb, w, a, d = (b - 0x80 for b in data[p:p + 5])
            metrics.append((lsb, rsb, w, a, d))
            p += 5
    else:
        (n,) = struct.unpack_from(bo + "i", data, p)
        p += 4
        for i in range(n):
            lsb, rsb, w, a, d, _ = struct.unpack_from(bo + "hhhhhH", data, p)
            metrics.append((lsb, rsb, w, a, d))
            p += 12

    # bitmaps
    fmt, bo, p = table(PCF_BITMAPS)
    pad = 1 << (fmt & 3)
    msbit = bool(fmt & 8)
    msbyte = bool(fmt & 4)
    unit = 1 << ((fmt >> 4) & 3)
    (n,) = struct.unpack_from(bo + "i", data, p)
    p += 4
    offsets = struct.unpack_from(bo + "%di" % n, data, p)
    p += 4 * n + 16
    bits = data[p:]

    def glyph(i):
        lsb, rsb, w, a, d = metrics[i]
        gw, gh = rsb - lsb, a + d
        stride = ((gw + 7) // 8 + pad - 1) // pad * pad
        rows = []
        for r in range(gh):
            row = bytearray(bits[offsets[i] + r * stride: offsets[i] + (r + 1) * stride])
            if msbyte != msbit and unit > 1:  # normalise byte order within scan units
                for u in range(0, len(row), unit):
                    row[u:u + unit] = row[u:u + unit][::-1]
            mask = 0
            for x in range(gw):
                byte = row[x // 8]
                bit = (byte >> (7 - x % 8)) & 1 if msbit else (byte >> (x % 8)) & 1
                if bit:
                    mask |= 1 << (x + lsb)
            rows.append((a, r, mask))
        return rows

    # encodings
    fmt, bo, p = table(PCF_BDF_ENCODINGS)
    min2, max2, min1, max1, default = struct.unpack_from(bo + "hhhhh", data, p)
    p += 10
    ncols = max2 - min2 + 1
    idx = struct.unpack_from(bo + "%dH" % (ncols * (max1 - min1 + 1)), data, p)

    cellw = max(m[2] for m in metrics)
    cells = []
    for ch in range(256):
        gi = 0xFFFF
        if min1 == 0 and min2 <= ch <= max2:
            gi = idx[ch - min2]
        if gi == 0xFFFF:
            gi = 0xFFFF if default < 0 else default
            if default >= 0 and min2 <= default <= max2:
                gi = idx[default - min2]
        rows = [0] * (ascent + descent)
        if gi != 0xFFFF and gi < len(metrics):
            for a, r, mask in glyph(gi):
                y = ascent - a + r
                if 0 <= y < len(rows):
                    rows[y] |= mask
        cells.append(rows)
    return cellw, ascent, descent, cells


def main():
    out = ["/* Generated by scripts/gen-fonts.py from the X11 misc-fixed fonts",
           "   (public domain). Do not edit. */",
           '#include "xw.h"', ""]
    entries = []
    for stem, names in FONTS:
        path = "%s/%s-ISO8859-1.pcf.gz" % (FONTDIR, stem)
        with gzip.open(path) as f:
            w, a, d, cells = parse_pcf(f.read())
        ident = "font_" + stem.lower()
        h = a + d
        flat = [row for c in cells for row in c]
        out.append("static const unsigned short %s_rows[%d] = {" % (ident, len(flat)))
        for i in range(0, len(flat), 16):
            out.append("  " + ",".join("0x%x" % v for v in flat[i:i + 16]) + ",")
        out.append("};")
        for n in names:
            entries.append('  {"%s", %d, %d, %d, %s_rows},' % (n, w, a, d, ident))
        assert w <= 16 and h > 0
    out.append("")
    out.append("const xw_font_data xw_fonts[] = {")
    out.extend(entries)
    out.append("  {0, 0, 0, 0, 0}")
    out.append("};")
    print("\n".join(out))


main()
